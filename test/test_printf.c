int main() {
    int number = 42;
    char letter = 'A';
    
    printf("Hello, World!\n");
    printf("Number: %d\n", number);
    printf("Character: %c\n", letter);
    int i = 10;
    while(i >= 0)
    {
        printf("Countdown: %d\n", i);
        i = i - 1;
    }
    printf("Multiple values: %d and %c HAHAHAHAH\n", number, letter);
    
    return 0;
}